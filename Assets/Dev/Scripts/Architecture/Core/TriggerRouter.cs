// Rôle (résumé)
// - Centralise les “triggers” identifiés par une string (triggerId) et exécute les actions associées.
// - Construit une table id ? [bindings] depuis LevelData.triggerBindings.
// - Expose Fire(id) pour déclencher toutes les actions liées à cet id (ex: ouvrir une TimedDoor).
//
// Invariants
// - AUCUNE modification d’API ni de logique existante.
// - On ajoute uniquement des commentaires, on ordonne visuellement les sections,
//   et on renomme quelques variables LOCALES trop génériques.
//
// Dépendances
// - LevelData.triggerBindings : liste de bindings { id, action, targetIndex, secondsOverride… }.
// - TimedDoorSystem : utilisé pour l’action TimedDoorOpen.
//

using System.Collections.Generic;
using UnityEngine;
using Sarabande.Levels;
using Sarabande.Core;
using Sarabande.Doors;

namespace Sarabande.Triggers
{
    public class TriggerRouter : MonoBehaviour
    {
        // ?????????????????????????????????????????????????????????????????????????????
        // Serialized fields (noms conservés)
        // ?????????????????????????????????????????????????????????????????????????????

        [Header("Context")]
        [SerializeField] private bool useLevelContext = true;
        [SerializeField] private Sarabande.Core.LevelContext levelContext;
        [SerializeField, HideInInspector] private LevelData levelData;

        [Header("Targets")]
        [SerializeField] private TimedDoorSystem timedDoorSystem;

        // ?????????????????????????????????????????????????????????????????????????????
        // Runtime
        // ?????????????????????????????????????????????????????????????????????????????

        // Table: triggerId ? liste de bindings
        private readonly Dictionary<string, List<LevelData.TriggerBinding>> _map = new();

        // ?????????????????????????????????????????????????????????????????????????????
        // Unity lifecycle
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Auto-récupère TimedDoorSystem si manquant, puis (re)construit la table des bindings.
        /// </summary>
        private void Awake()
        {
            if (!timedDoorSystem)
                timedDoorSystem = FindFirstObjectByType<TimedDoorSystem>(FindObjectsInactive.Include);

            Rebuild();
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Build / Map
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Reconstruit la table triggerId ? bindings à partir de <see cref="levelData"/>.
        /// </summary>
        private void Rebuild()
        {
            _map.Clear();
            if (levelData == null || levelData.triggerBindings == null) return;

            foreach (var binding in levelData.triggerBindings)
            {
                if (string.IsNullOrEmpty(binding.id)) continue;

                if (!_map.TryGetValue(binding.id, out var listForId))
                {
                    listForId = new List<LevelData.TriggerBinding>();
                    _map[binding.id] = listForId;
                }
                listForId.Add(binding);
            }
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Public API
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Déclenche toutes les actions liées à ce <paramref name="id"/>.
        /// Pour l’instant, seule l’action TimedDoorOpen est gérée.
        /// </summary>
        public void Fire(string id)
        {
            if (string.IsNullOrEmpty(id)) return;
            if (!_map.TryGetValue(id, out var bindingsForId)) return;

            foreach (var binding in bindingsForId)
            {
                switch (binding.action)
                {
                    case LevelData.TriggerActionKind.TimedDoorOpen:
                        if (timedDoorSystem == null) continue;

                        // Sécurise l’index de porte, calcule la durée:
                        // - secondsOverride > 0 ? on l’utilise,
                        // - sinon on récupère l’openSeconds de la porte dans LevelData (fallback 1s).
                        int doorIndex = Mathf.Max(0, binding.targetIndex);

                        float seconds =
                            (binding.secondsOverride > 0f)
                                ? binding.secondsOverride
                                : (levelData != null && levelData.timedDoors != null
                                   && doorIndex < levelData.timedDoors.Count
                                        ? Mathf.Max(0.1f, levelData.timedDoors[doorIndex].openSeconds)
                                        : 1f);

                        timedDoorSystem.OpenDoor(doorIndex, seconds);
                        break;

                        // (plus tard) autres actions ici
                }
            }
        }

        /// <summary>
        /// Retourne la liste des index de portes potentiellement ouvertes par ce <paramref name="id"/>.
        /// Utile pour les systèmes qui doivent “se réarmer” après DoorClosed, etc.
        /// </summary>
        public List<int> GetTimedDoorTargetsForId(string id)
        {
            var result = new List<int>();
            if (string.IsNullOrEmpty(id)) return result;
            if (!_map.TryGetValue(id, out var bindingsForId)) return result;

            foreach (var binding in bindingsForId)
            {
                if (binding.action == LevelData.TriggerActionKind.TimedDoorOpen)
                    result.Add(Mathf.Max(0, binding.targetIndex));
            }
            return result;
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // LevelContext wiring (inchangé)
        // ?????????????????????????????????????????????????????????????????????????????
        //
        // NOTE: ce script dans l’export ne montre pas l’attachement au LevelContext.
        // S’il existe dans ta base (pattern commun aux autres systèmes), on le garde identique.
        // Ici, on n’introduit aucune logique supplémentaire pour rester 100% non-cassant.
    }
}
