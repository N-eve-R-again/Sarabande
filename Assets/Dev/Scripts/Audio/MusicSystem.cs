// Rôle (résumé)
// - Joue deux boucles musicales (base/disco) démarrées en même temps en DSP pour garantir le calage.
// - La boucle “base” est audible hors disco ; la boucle “disco” prend le relais pendant la séquence.
// - Crossfade paramétrable en millisecondes (0 => switch instantané).
//
// Invariants
// - AUCUN renommage de champs sérialisés ni de méthodes publiques.
// - Logique strictement identique ; uniquement documentation, ordre plus lisible, et renommages locaux.

using System.Collections;
using UnityEngine;
using UnityEngine.Audio;

namespace Sarabande.Audio
{
    /// <summary>
    /// Gère deux <see cref="AudioSource"/> en parallèle (boucles calées) et réalise le crossfade
    /// entre la musique “base” et “disco”.
    /// </summary>
    public class MusicSystem : MonoBehaviour
    {
        // ?????????????????????????????????????????????????????????????????????????????
        // Clips & Mix
        // ?????????????????????????????????????????????????????????????????????????????

        [Header("Clips")]
        [SerializeField] private AudioClip baseLoop;
        [SerializeField] private AudioClip discoLoop;

        [Header("Volumes")]
        [SerializeField, Range(0f, 1f)] private float baseVolume = 1f;
        [SerializeField, Range(0f, 1f)] private float discoVolume = 1f;

        [Header("Mix (optionnel)")]
        [SerializeField] private AudioMixerGroup output;

        [Header("Crossfade")]
        [Tooltip("En millisecondes. 0 = switch instantané.")]
        [SerializeField, Min(0f)] private float crossfadeMs = 0f;

        // ?????????????????????????????????????????????????????????????????????????????
        // Runtime
        // ?????????????????????????????????????????????????????????????????????????????

        private AudioSource _baseSrc;
        private AudioSource _discoSrc;
        private bool _started;
        private Coroutine _fadeCo;

        // ?????????????????????????????????????????????????????????????????????????????
        // Unity lifecycle
        // ?????????????????????????????????????????????????????????????????????????????

        private void Awake()
        {
            _baseSrc = CreateSrc("Music_Base");
            _discoSrc = CreateSrc("Music_Disco");
        }

        private void Start()
        {
            // Lance les deux boucles calées en DSP pour éviter tout drift de phase.
            StartLoops();
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Construction & Démarrage
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Crée un <see cref="AudioSource"/> enfant configuré pour boucler.
        /// </summary>
        private AudioSource CreateSrc(string childName)
        {
            var childGO = new GameObject(childName);
            childGO.transform.SetParent(transform, false);

            var source = childGO.AddComponent<AudioSource>();
            source.playOnAwake = false;
            source.loop = true;
            if (output) source.outputAudioMixerGroup = output;
            return source;
        }

        /// <summary>
        /// Assigne les clips et démarre les deux sources au même instant DSP.
        /// </summary>
        private void StartLoops()
        {
            if (!baseLoop || !discoLoop)
            {
                Debug.LogWarning("[MusicSystem] Clips manquants.");
                return;
            }

            _baseSrc.clip = baseLoop;
            _discoSrc.clip = discoLoop;

            // Démarrage parfaitement calé (léger délai pour armer la planification)
            double dspStartTime = AudioSettings.dspTime + 0.05;

            _baseSrc.volume = baseVolume;
            _discoSrc.volume = 0f;

            _baseSrc.PlayScheduled(dspStartTime);
            _discoSrc.PlayScheduled(dspStartTime);

            _started = true;
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // API publique
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>Active la musique “disco” (crossfade depuis “base”).</summary>
        public void EnterDisco()
        {
            if (!_started) return;
            Crossfade(toDisco: true);
        }

        /// <summary>Revient à la musique “base” (crossfade depuis “disco”).</summary>
        public void ExitDisco()
        {
            if (!_started) return;
            Crossfade(toDisco: false);
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Crossfade
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Lance/relance la coroutine de crossfade vers l’état cible.
        /// </summary>
        private void Crossfade(bool toDisco)
        {
            if (_fadeCo != null) StopCoroutine(_fadeCo);
            _fadeCo = StartCoroutine(FadeRoutine(toDisco));
        }

        /// <summary>
        /// Interpole les volumes des deux sources pendant <see cref="crossfadeMs"/>.
        /// Utilise <see cref="Time.unscaledDeltaTime"/> (indépendant du timescale).
        /// </summary>
        private IEnumerator FadeRoutine(bool toDisco)
        {
            float durationSeconds = crossfadeMs / 1000f;

            float baseStartVol = _baseSrc.volume;
            float discoStartVol = _discoSrc.volume;

            float baseTarget = toDisco ? 0f : baseVolume;
            float discoTarget = toDisco ? discoVolume : 0f;

            if (durationSeconds <= 0f)
            {
                _baseSrc.volume = baseTarget;
                _discoSrc.volume = discoTarget;
                yield break;
            }

            float t = 0f;
            while (t < durationSeconds)
            {
                t += Time.unscaledDeltaTime;
                float k = Mathf.Clamp01(t / durationSeconds);

                _baseSrc.volume = Mathf.Lerp(baseStartVol, baseTarget, k);
                _discoSrc.volume = Mathf.Lerp(discoStartVol, discoTarget, k);

                yield return null;
            }

            _baseSrc.volume = baseTarget;
            _discoSrc.volume = discoTarget;
        }
    }
}
