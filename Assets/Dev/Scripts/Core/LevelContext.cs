// Rôle (résumé)
// - Source unique de LevelData pour la scène/niveau.
// - Notifie tous les systèmes abonnés via l’événement LevelDataChanged à CHAQUE changement,
//   en mode Éditeur (OnValidate) et en mode Play (OnEnable + setter).
//
// Invariants (ne pas casser)
// - AUCUN renommage d’API publique/privée.
// - Même logique: RaiseChanged() est appelé sur OnEnable, OnValidate et à chaque set de LevelData.
// - Exécution très tôt grâce à DefaultExecutionOrder(-1000) pour que les autres systèmes puissent s’abonner ensuite.

using UnityEngine;
using Sarabande.Levels;

namespace Sarabande.Core
{
    /// <summary>
    /// Source unique de <see cref="LevelData"/> pour le niveau.
    /// Diffuse un événement à chaque changement (Editor + Play).
    /// </summary>
    [DisallowMultipleComponent]
    [ExecuteAlways]
    [DefaultExecutionOrder(-1000)]
    public class LevelContext : MonoBehaviour
    {
        // ?????????????????????????????????????????????????????????????????????????????
        // Serialized data (noms conservés)
        // ?????????????????????????????????????????????????????????????????????????????

        [SerializeField] private LevelData levelData;

        /// <summary>
        /// Données de niveau courantes.
        /// Déclenche <see cref="LevelDataChanged"/> à chaque nouvelle valeur.
        /// </summary>
        public LevelData LevelData
        {
            get => levelData;
            set
            {
                if (levelData == value) return; // rien à faire si identique (évite des rebuild inutiles)
                levelData = value;
                RaiseChanged();
            }
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Events
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Émis à chaque fois que <see cref="LevelData"/> change (Editor + Play).
        /// La valeur peut être null (ex: reset de référence dans l’Inspector).
        /// </summary>
        public event System.Action<LevelData> LevelDataChanged;

        // ?????????????????????????????????????????????????????????????????????????????
        // Unity lifecycle
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// En mode Play ET Editor, pousse l’état courant pour que les listeners se synchronisent,
        /// y compris après domain reload / enter play.
        /// </summary>
        private void OnEnable() => RaiseChanged();

#if UNITY_EDITOR
        /// <summary>
        /// En Éditeur: appelé quand la valeur change dans l’Inspector (glisser/déposer, undo/redo, etc.).
        /// On propage immédiatement le changement pour les composants qui écoutent en Editor.
        /// </summary>
        private void OnValidate() => RaiseChanged();
#endif

        // ?????????????????????????????????????????????????????????????????????????????
        // Internals
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Notifie les abonnés du contexte (si présents).
        /// Pas d’allocation superflue, on appelle directement l’événement.
        /// </summary>
        private void RaiseChanged() => LevelDataChanged?.Invoke(levelData);
    }
}