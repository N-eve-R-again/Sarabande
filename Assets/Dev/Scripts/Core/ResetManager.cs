// Rôle
// - Chef d’orchestre du reset de niveau.
// - Recense tous les IResettable présents dans la scène (y compris inactifs).
// - Détermine un ordre de reset simple et stable pour éviter les effets de bord.
// - Peut afficher un overlay de rewind et jouer un SFX avant d’exécuter le reset.
//
// Invariants
// - Aucun renommage d’API publique ou de champs sérialisés.
// - Pas de logique nouvelle, uniquement des commentaires et un rangement visuel.
// - Le reset doit pouvoir être appelé à tout moment sans dépendre d’un état caché.

using System.Collections.Generic;
using System.Collections;
using UnityEngine;

namespace Sarabande.Core
{
    /// <summary>
    /// Gère les resets de niveau:
    /// 1) collecte les objets <see cref="IResettable"/>,
    /// 2) les trie par priorité simple,
    /// 3) appelle <see cref="IResettable.ResetToInitial"/> sur chacun.
    /// Peut précéder ce reset d’un court "rewind" visuel et sonore.
    /// </summary>
    public class ResetManager : MonoBehaviour
    {
        // ?????????????????????????????????????????????????????????????????????????????
        // Serialized fields (noms conservés)
        // ?????????????????????????????????????????????????????????????????????????????

        [Header("Discovery")]
        [Tooltip("Si vrai, la liste des IResettable est collectée au Awake.")]
        [SerializeField] private bool findOnAwake = true;

        [Header("Rewind UI/Timing")]
        [Tooltip("Overlay facultatif pour afficher un effet de rewind pendant quelques secondes.")]
        [SerializeField] private Sarabande.UI.RewindOverlay rewindOverlay;
        [Tooltip("Durée d’affichage de l’overlay avant le reset effectif.")]
        [SerializeField, Min(0f)] private float rewindDuration = 1f;

        [Header("Audio")]
        [Tooltip("SFX joué quand l’overlay de rewind s’affiche.")]
        [SerializeField] private AudioClip rewindClip;
        [SerializeField, Range(0f, 1f)] private float rewindVolume = 1f;
        [Tooltip("0 = son 2D (UI), 1 = son 3D. L’overlay étant de l’UI, 0 est logique par défaut.")]
        [SerializeField, Range(0f, 1f)] private float rewindSpatialBlend = 0f;

        // ?????????????????????????????????????????????????????????????????????????????
        // Runtime
        // ?????????????????????????????????????????????????????????????????????????????

        // Cache local des cibles à reset. Reconstitué à chaque ResetAll pour ne rien oublier.
        private readonly List<IResettable> _resettables = new();

        /// <summary>
        /// Vrai pendant la fenêtre de rewind et l’exécution de ResetAll.
        /// Utile pour que d’autres systèmes gèlent leurs actions pendant ce laps de temps.
        /// </summary>
        public bool IsResetInProgress { get; private set; }

        // ?????????????????????????????????????????????????????????????????????????????
        // Unity lifecycle
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Au démarrage, on peut déjà recenser les IResettable si demandé.
        /// </summary>
        private void Awake()
        {
            if (findOnAwake) CollectResettables();
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Public API
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Re-scanne la scène pour reconstruire la liste des <see cref="IResettable"/>.
        /// Appeler cette méthode si des objets sont instanciés ou détruits dynamiquement.
        /// </summary>
        public void CollectResettables()
        {
            _resettables.Clear();

            // On inclut aussi les GameObjects inactifs pour que leur ResetToInitial soit appelé
            // s’ils participent à l’état de la scène au redémarrage.
            var allMonoBehaviours = FindObjectsByType<MonoBehaviour>(
                FindObjectsInactive.Include,
                FindObjectsSortMode.None
            );

            foreach (var component in allMonoBehaviours)
            {
                // Pas d’allocation intermédiaire: on filtre et on ajoute
                if (component is IResettable resettable)
                    _resettables.Add(resettable);
            }
        }

        /// <summary>
        /// Exécute immédiatement le reset de tous les <see cref="IResettable"/> trouvés.
        /// L’ordre est déterministe et pensé pour éviter les conflits de positions.
        /// </summary>
        public void ResetAll()
        {
            // On repart d’un scan frais à chaque appel, cela évite d’oublier
            // de nouveaux objets et évite de conserver des références détruites.
            CollectResettables();

            // Ordre très simple:
            // 0 = entités qui bougent (héros, NME),
            // 1 = systèmes qui bloquent des arêtes/chemins (gates, timed doors),
            // 2 = tout le reste.
            _resettables.Sort((a, b) => ResetOrder(a).CompareTo(ResetOrder(b)));

            // Appel synchrone: chaque ResetToInitial doit être rapide et side-effect safe.
            foreach (var resettable in _resettables)
                resettable.ResetToInitial();
        }

        /// <summary>
        /// Lance un rewind court, puis appelle <see cref="ResetAll"/>.
        /// Si un reset est déjà en cours, on ignore.
        /// </summary>
        public void ResetWithRewind()
        {
            if (IsResetInProgress) return;
            StartCoroutine(ResetWithRewindRoutine());
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Internals
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Retourne la priorité d’un IResettable dans l’ordre de reset.
        /// Plus le nombre est petit, plus l’élément est reset tôt.
        /// </summary>
        private static int ResetOrder(IResettable resettable)
        {
            // Priorité 0: acteurs mobiles. Ils libèrent/consolident des cases
            // avant que des systèmes ne referment des portes ou des grilles.
            if (resettable is Sarabande.Player.HeroController) return 0;
            if (resettable is Sarabande.NME.NMEController) return 0;

            // Priorité 1: systèmes d’arêtes bloquantes et de cheminement.
            if (resettable is Sarabande.Gates.GridGateSystem) return 1;
            if (resettable is Sarabande.Doors.TimedDoorSystem) return 1;

            // Priorité 2: tout le reste.
            return 2;
        }

        /// <summary>
        /// Affiche l’overlay de rewind, joue un SFX, attend la durée,
        /// puis appelle <see cref="ResetAll"/>. Protège le flag <see cref="IsResetInProgress"/>.
        /// </summary>
        private IEnumerator ResetWithRewindRoutine()
        {
            IsResetInProgress = true;

            // UI overlay si assigné
            if (rewindOverlay) rewindOverlay.ShowFor(rewindDuration);

            // SFX via AudioHub si disponible. SpatialBlend = 0 par défaut pour un son d’UI.
            Sarabande.Audio.AudioHub.I?.PlaySFXAt(
                clip: rewindClip,
                pos: transform.position,
                volume: rewindVolume,
                spatialBlend: rewindSpatialBlend,
                minDistance: 1f,
                maxDistance: 20f
            );

            // Petite attente visuelle/sonore
            yield return new WaitForSeconds(rewindDuration);

            // Reset synchrone
            ResetAll();

            // Déblocage global
            IsResetInProgress = false;
        }

        // ?????????????????????????????????????????????????????????????????????????????
        // Editor helpers
        // ?????????????????????????????????????????????????????????????????????????????

        /// <summary>
        /// Raccourci pratique pour tester depuis l’Inspector.
        /// </summary>
        [ContextMenu("Reset Level Now")]
        private void ContextResetNow() => ResetAll();
    }
}
